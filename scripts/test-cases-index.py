#!/usr/bin/env python3
"""
Build docs/test-cases/TEST-CASES.md (all test cases in one file) from the per-feature files in
docs/test-cases/features/. The feature files are the source of truth; never edit TEST-CASES.md by hand.

  python3 scripts/test-cases-index.py              # rebuild TEST-CASES.md and check coverage
  python3 scripts/test-cases-index.py --sprint 02  # list one sprint's cases (for sprint-testing)
  python3 scripts/test-cases-index.py --check      # only check (exit 1 on gaps or duplicates)
"""
import os, re, sys
from collections import Counter, defaultdict

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIR = os.path.join(ROOT, 'docs', 'test-cases')
FEATURES = os.path.join(DIR, 'features')
SOURCE = os.path.join(ROOT, 'docs', '07-test-cases.md')
COLS = ['ID', 'Title', 'Sprint', 'Level', 'Pri', 'Story / AC', 'Steps / input', 'Expected', 'Script › test', 'Status']
STATUS_ORDER = ['✅', '❌', '☐', '⏭', 'M']


def split_row(line):
    cells, cur, i = [], '', 0
    body = line.strip()[1:-1]
    while i < len(body):
        if body[i] == '\\' and i + 1 < len(body) and body[i + 1] == '|':
            cur += '\\|'; i += 2; continue
        if body[i] == '|':
            cells.append(cur.strip()); cur = ''
        else:
            cur += body[i]
        i += 1
    cells.append(cur.strip())
    return cells


def load():
    features, rows = [], []
    for name in sorted(os.listdir(FEATURES)):
        if not name.endswith('.md'):
            continue
        text = open(os.path.join(FEATURES, name)).read()
        title = re.search(r'^# (.+)$', text, re.M).group(1)
        code = name.split('-')[0]
        features.append((code, title.split('·', 1)[1].strip(), name))
        for line in text.split('\n'):
            if line.startswith('| ') and not line.startswith('| ID ') and not line.startswith('|---'):
                cells = split_row(line)
                if len(cells) != len(COLS):
                    sys.exit(f'{name}: expected {len(COLS)} columns, got {len(cells)}: {line[:80]}')
                rows.append(dict(zip(COLS, cells), feature=code, file=name))
    return features, rows


def check(rows):
    problems = []
    source_ids = set(re.findall(r'^\| (TC-[A-Z]+(?:-[A-Z]+)?-\d+) \|', open(SOURCE).read(), re.M))
    have = {r['ID'] for r in rows}
    for missing in sorted(source_ids - have):
        problems.append(f'{missing} is in 07-test-cases.md but in no feature file')
    dupes = [k for k, n in Counter((r['ID'], r['Sprint'], r['Title']) for r in rows).items() if n > 1]
    problems += [f'duplicate row {d}' for d in dupes]
    for r in rows:
        if r['Status'].split()[0] not in STATUS_ORDER:
            problems.append(f"{r['ID']}: unknown status {r['Status']!r}")
        if not re.match(r'^S\d\d$', r['Sprint']):
            problems.append(f"{r['ID']}: bad sprint {r['Sprint']!r}")
    return problems


def status_key(s):
    return s.split()[0] if s else '☐'


def build(features, rows):
    by_feature = defaultdict(list)
    for r in rows:
        by_feature[r['feature']].append(r)
    total = Counter(status_key(r['Status']) for r in rows)
    sprints = sorted({r['Sprint'] for r in rows})
    out = [
        '# CanteenQ · All test cases',
        '',
        '> Generated by `python3 scripts/test-cases-index.py` from [`features/`](features/). '
        'Edit the feature files, then re-run the script. Do not edit this file by hand.',
        '',
        f'**{len(rows)} cases** ({sum(r["ID"].startswith("TC-") for r in rows)} test-case rows from '
        f'[07-test-cases.md](../07-test-cases.md), {sum(r["ID"].startswith("EC-") for r in rows)} edge cases) · '
        + ' · '.join(f'{s} {total[s]}' for s in STATUS_ORDER if total[s]),
        '',
        'Legend: ✅ pass · ❌ fail (BUG id) · ☐ not run yet · ⏭ skipped (reason) · M manual. '
        'Levels: Unit · API · UI · Manual · Non-functional. How the scripts are organised and gated: [README.md](README.md).',
        '',
        '## Features',
        '',
        '| # | Feature | Cases | Test cases | Edge cases | Sprints | Status |',
        '|---|---|---|---|---|---|---|',
    ]
    for code, name, fname in features:
        rs = by_feature[code]
        st = Counter(status_key(r['Status']) for r in rs)
        out.append(
            f'| {code} | [{name}](features/{fname}) | {len(rs)} | {sum(r["ID"].startswith("TC-") for r in rs)} | '
            f'{sum(r["ID"].startswith("EC-") for r in rs)} | {", ".join(sorted({r["Sprint"] for r in rs}))} | '
            + ' '.join(f'{s}{st[s]}' for s in STATUS_ORDER if st[s]) + ' |'
        )
    out += ['', '## By sprint', '', '| Sprint | Cases | Status |', '|---|---|---|']
    for s in sprints:
        rs = [r for r in rows if r['Sprint'] == s]
        st = Counter(status_key(r['Status']) for r in rs)
        out.append(f'| {s} | {len(rs)} | ' + ' '.join(f'{k}{st[k]}' for k in STATUS_ORDER if st[k]) + ' |')
    out += ['', '## All test cases', '']
    for code, name, fname in features:
        out += [f'### {code} · {name}', '', f'Details (steps, expected, script): [features/{fname}](features/{fname})', '',
                '| ID | Title | Sprint | Level | Pri | Status |', '|---|---|---|---|---|---|']
        for r in by_feature[code]:
            out.append(f"| {r['ID']} | {r['Title']} | {r['Sprint']} | {r['Level']} | {r['Pri']} | {r['Status']} |")
        out.append('')
    return '\n'.join(out)


def main():
    features, rows = load()
    problems = check(rows)
    if '--sprint' in sys.argv:
        s = 'S' + sys.argv[sys.argv.index('--sprint') + 1].zfill(2)
        for r in rows:
            if r['Sprint'] == s:
                print(f"{r['Status']}  {r['ID']:<16} {r['Level']:<8} {r['file']:<28} {r['Title']}")
        return
    for p in problems:
        print('PROBLEM:', p)
    if '--check' in sys.argv:
        sys.exit(1 if problems else 0)
    open(os.path.join(DIR, 'TEST-CASES.md'), 'w').write(build(features, rows) + '\n')
    print(f'Wrote docs/test-cases/TEST-CASES.md: {len(rows)} cases in {len(features)} features'
          + (f', {len(problems)} problems' if problems else ', no gaps'))
    sys.exit(1 if problems else 0)


if __name__ == '__main__':
    main()
